"""Extract the supplied workbook into a browser module; Python stdlib only."""
from pathlib import Path
import hashlib
import json
import re
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "五十音转空耳对照表.xlsx"
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}


def build():
    with zipfile.ZipFile(SOURCE) as archive:
        strings = []
        if "xl/sharedStrings.xml" in archive.namelist():
            strings = ["".join(t.text or "" for t in si.findall(".//m:t", NS))
                       for si in ET.fromstring(archive.read("xl/sharedStrings.xml")).findall("m:si", NS)]
        cells = {}
        sheet = ET.fromstring(archive.read("xl/worksheets/sheet1.xml"))
        for cell in sheet.findall(".//m:sheetData/m:row/m:c", NS):
            value = cell.find("m:v", NS)
            text = value.text if value is not None else ""
            if cell.get("t") == "s":
                text = strings[int(text)]
            elif cell.get("t") == "inlineStr":
                text = "".join(t.text or "" for t in cell.findall(".//m:t", NS))
            cells[cell.get("r")] = (text or "").strip()

    mapping, syllables = {}, set()

    def add(romaji, chinese):
        if not re.fullmatch(r"[a-z]+", romaji):
            raise ValueError(f"Invalid romaji: {romaji}")
        syllables.add(romaji)
        if chinese:
            if romaji in mapping and mapping[romaji] != chinese:
                raise ValueError(f"Conflicting mapping: {romaji}")
            mapping[romaji] = chinese

    # The basic grid alternates kana/romaji rows and Chinese rows.
    for row in range(2, 21, 2):
        for col in "BCDEF":
            match = re.search(r"\[([a-z/]+)\]", cells.get(f"{col}{row}", ""))
            if match:
                for romaji in match[1].split("/"):
                    add(romaji, cells.get(f"{col}{row + 1}", ""))
    add(cells["E23"], cells["E24"])

    # Voiced and semi-voiced rows put the Chinese before each romaji cell.
    for row in (26, 27, 28, 29, 31):
        for roman_col, chinese_col in (("E", "D"), ("I", "H"), ("M", "L"), ("Q", "P"), ("X", "W")):
            match = re.match(r"([a-z]+)\s+\[", cells.get(f"{roman_col}{row}", ""))
            if match:
                add(match[1], cells.get(f"{chinese_col}{row}", ""))

    # Contracted sounds are listed but have no Chinese equivalents: keep them.
    for row in range(34, 45):
        for col in ("F", "L", "T"):
            match = re.match(r"([a-z]+)\s+\[", cells.get(f"{col}{row}", ""))
            if match:
                add(match[1], "")

    assert all(mapping.get(key) == key for key in ("ki", "ke", "hi"))
    meta = {"file": SOURCE.name, "sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest()}
    js = "// Generated by scripts/build-soramimi.py. Edit the source workbook, then regenerate.\n"
    js += "export const source = Object.freeze(" + json.dumps(meta, ensure_ascii=False, indent=2) + ");\n"
    js += "export const mapping = Object.freeze(" + json.dumps(dict(sorted(mapping.items())), ensure_ascii=False, indent=2) + ");\n"
    js += "export const syllables = Object.freeze(" + json.dumps(sorted(syllables, key=lambda s: (-len(s), s)), ensure_ascii=False) + ");\n"
    (ROOT / "public" / "soramimi-data.mjs").write_text(js, encoding="utf-8", newline="\n")
    print(f"Extracted {len(mapping)} mappings and {len(syllables)} syllables.")


if __name__ == "__main__":
    build()
